/**
 * The scanned tufts as GPU instances: one InstancedMesh per scanned tuft, all sharing the
 * scan's own material with a few lines added to its shader:
 *   vertex    the wind: each blade bends by the square of its height in the tuft, two sines out of
 *             phase per instance, so neighbours never move in step
 *   fragment  the light through the blades (translucency): a forward-scattering lobe toward the sun,
 *             strongest at the tips, plus a darker, cooler foot where the tuft meets the moss
 */
export function GrassMedium02Field({ instances, sunFrom, sunColor = '#ffd89a', sway = 0.02, translucency = 0.9 }: GrassFieldProps) {
  const { nodes, materials } = useGLTF(URL) as unknown as GLTFResult

  const tufts = useMemo(() => TUFTS.map((k) => footed(nodes[k])), [nodes])

  const uniforms = useMemo(
    () => ({
      uTime: { value: 0 },
      uSway: { value: sway },
      uSunView: { value: new THREE.Vector3(0, 1, 0) },
      uSunColor: { value: new THREE.Color(sunColor) },
      uTrans: { value: translucency },
    }),
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [],
  )
  useEffect(() => {
    uniforms.uSway.value = sway
    uniforms.uTrans.value = translucency
    uniforms.uSunColor.value.set(sunColor)
  }, [uniforms, sway, translucency, sunColor])

  const material = useMemo(() => {
    const m = materials.grass_medium_02.clone()
    m.side = THREE.DoubleSide
    m.alphaTest = 0.45
    m.transparent = false
    m.roughness = 0.8
    m.onBeforeCompile = (shader) => {
      Object.assign(shader.uniforms, uniforms)
      shader.vertexShader = shader.vertexShader
        .replace(
          '#include <common>',
          `#include <common>
uniform float uTime;
uniform float uSway;
attribute float aHeight;
varying float vH;`,
        )
        .replace(
          '#include <begin_vertex>',
          `#include <begin_vertex>
vec4 ip = instanceMatrix * vec4(0.0, 0.0, 0.0, 1.0);
float ph = ip.x * 3.1 + ip.z * 2.3;
float hk = clamp(position.y / max(aHeight, 1e-3), 0.0, 1.0);
vH = hk;
float gust = sin(uTime * 1.1 + ph) * 0.7 + sin(uTime * 2.3 + ph * 1.7) * 0.3;
float s = uSway / max(length(instanceMatrix[0].xyz), 1e-3);
transformed.x += gust * s * hk * hk;
transformed.z += cos(uTime * 0.9 + ph * 1.3) * s * 0.45 * hk * hk;`,
        )
      shader.fragmentShader = shader.fragmentShader
        .replace(
          '#include <common>',
          `#include <common>
uniform vec3 uSunView;
uniform vec3 uSunColor;
uniform float uTrans;
varying float vH;`,
        )
        .replace(
          '#include <emissivemap_fragment>',
          `#include <emissivemap_fragment>
{
  // lift the scan's baked dark texels: a blade of grass must never draw a black speck
  float gl = dot(diffuseColor.rgb, vec3(0.2126, 0.7152, 0.0722));
  diffuseColor.rgb = mix(diffuseColor.rgb, max(diffuseColor.rgb, vec3(0.16, 0.15, 0.10)), smoothstep(0.22, 0.02, gl) * 0.85);
  // a dry reed is a warm, light thing: pull the scan's dark fibres toward sunlit straw
  diffuseColor.rgb = mix(diffuseColor.rgb, vec3(0.52, 0.46, 0.28), 0.5);
  // the foot of the tuft sits in the moss's shade; the tips catch the light
  diffuseColor.rgb *= mix(0.78, 1.12, smoothstep(0.0, 0.75, vH));
  // light through the blades: forward scattering toward the sun, stronger at the thin tips
  vec3 V = normalize(vViewPosition);
  float fwd = pow(clamp(dot(-V, uSunView), 0.0, 1.0), 3.0);
  float wrap = 0.35 + 0.65 * fwd;
  totalEmissiveRadiance += diffuseColor.rgb * uSunColor * uTrans * wrap * smoothstep(0.15, 1.0, vH);
}`,
        )
    }
    m.customProgramCacheKey = () => 'grass-medium-02-field'
    return m
  }, [materials, uniforms])

  // per-tuft instance buffers
  const meshes = useMemo(() => {
    const dummy = new THREE.Object3D()
    return tufts.map((t, k) => {
      const list = instances.filter((i) => i.tuft === k)
      const geometry = t.geometry.clone()
      geometry.setAttribute('aHeight', new THREE.BufferAttribute(new Float32Array(geometry.getAttribute('position').count).fill(t.height), 1))
      const mesh = new THREE.InstancedMesh(geometry, material, Math.max(1, list.length))
      mesh.count = list.length
      list.forEach((i, j) => {
        dummy.position.set(i.x, i.y, i.z)
        dummy.rotation.set(0, i.yaw, 0)
        dummy.scale.setScalar(i.scale)
        dummy.updateMatrix()
        mesh.setMatrixAt(j, dummy.matrix)
        mesh.setColorAt(j, i.tint)
      })
      mesh.instanceMatrix.needsUpdate = true
      if (mesh.instanceColor) mesh.instanceColor.needsUpdate = true
      mesh.frustumCulled = false
      return mesh
    })
  }, [tufts, instances, material])

  useEffect(() => () => meshes.forEach((m) => m.geometry.dispose()), [meshes])

  const sun = useMemo(() => new THREE.Vector3(...sunFrom).normalize(), [sunFrom])
  useFrame((state) => {
    uniforms.uTime.value = state.clock.elapsedTime
    uniforms.uSunView.value.copy(sun).transformDirection(state.camera.matrixWorldInverse)
  })

  return (
    <group dispose={null}>
      {meshes.map((m, k) => (
        <primitive key={k} object={m} />
      ))}
    </group>
  )
}
