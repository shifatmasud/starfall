/**
 * One tuft as a plain float geometry with its foot at the origin. The glb is quantized (int16
 * positions dequantized by the node's position/scale), so the node transform is baked in here and
 * the tuft re-centred, ready to be placed by an instance matrix.
 */
function footed(mesh: THREE.Mesh): { geometry: THREE.BufferGeometry; height: number } {
  const src = mesh.geometry
  const m = new THREE.Matrix4().compose(mesh.position, mesh.quaternion, mesh.scale)
  const p = src.getAttribute('position')
  const n = src.getAttribute('normal')
  const uv = src.getAttribute('uv')
  const pos = new Float32Array(p.count * 3)
  const nrm = new Float32Array(p.count * 3)
  const tex = new Float32Array(p.count * 2)
  const v = new THREE.Vector3()
  const nm = new THREE.Matrix3().getNormalMatrix(m)
  for (let i = 0; i < p.count; i++) {
    v.fromBufferAttribute(p, i).applyMatrix4(m)
    pos.set([v.x, v.y, v.z], i * 3)
    if (n) {
      v.fromBufferAttribute(n, i).applyMatrix3(nm).normalize()
      nrm.set([v.x, v.y, v.z], i * 3)
    }
    if (uv) tex.set([uv.getX(i), uv.getY(i)], i * 2)
  }
  const g = new THREE.BufferGeometry()
  g.setAttribute('position', new THREE.BufferAttribute(pos, 3))
  g.setAttribute('normal', new THREE.BufferAttribute(nrm, 3))
  g.setAttribute('uv', new THREE.BufferAttribute(tex, 2))
  if (src.index) g.setIndex(Array.from(src.index.array as ArrayLike<number>))
  g.computeBoundingBox()
  const b = g.boundingBox!
  g.translate(-(b.min.x + b.max.x) / 2, -b.min.y, -(b.min.z + b.max.z) / 2)
  g.computeBoundingBox()
  g.computeBoundingSphere()
  return { geometry: g, height: g.boundingBox!.max.y }
}

